"""SQLite schema baseline.

SQLite installs don't replay the migration history. A new SQLite database gets the schema the
migrations produce on PostgreSQL (sqlite_baseline.sql, generated from a freshly migrated
PostgreSQL database), its seed rows, and every migration the baseline covers recorded as applied.
Migrations added after the baseline must handle db_type == 'sqlite' themselves.

Column names are lowercase, as PostgreSQL stores them, so queries written for PostgreSQL read
the same column names on SQLite.

Regenerate after a schema change (the integration suite fails until you do):
    python -m database_functions.sqlite_baseline "postgresql://user:pw@host:port/freshly_migrated_db"
Check without writing: add --check.
"""

import json
import os
import re
import secrets
import string
import sys
from decimal import Decimal
from datetime import datetime, date

BASELINE_PATH = os.path.join(os.path.dirname(__file__), "sqlite_baseline.sql")

# Seed values that must differ per install; the generator writes these placeholders instead.
INSTALL_PLACEHOLDERS = {
    ("AppSettings", "encryptionkey"): ":encryption_key",
    ("APIKeys", "apikey"): ":bg_api_key",
    ("Users", "hashed_pw"): ":bg_password_hash",
}

TYPE_MAP = {
    "integer": "INTEGER",
    "smallint": "INTEGER",
    "bigint": "BIGINT",
    "boolean": "BOOLEAN",
    "text": "TEXT",
    "character varying": "TEXT",
    "character": "TEXT",
    "timestamp without time zone": "TIMESTAMP",
    "timestamp with time zone": "TIMESTAMP",
    "date": "DATE",
    "double precision": "REAL",
    "real": "REAL",
    "numeric": "REAL",
    "jsonb": "TEXT",
    "json": "TEXT",
    "ARRAY": "TEXT",
    "bytea": "BLOB",
}

CAST_RE = re.compile(
    r"::(?:character varying|character|double precision|timestamp without time zone|"
    r"timestamp with time zone|\"?[a-z_]+\"?)(?:\[\])?"
)


def translate_expr(expr: str) -> str:
    """PostgreSQL CHECK / index-predicate text -> SQLite."""
    s = CAST_RE.sub("", expr)
    # x = ANY ((ARRAY['a', 'b'])) -> x IN ('a', 'b')
    s = re.sub(r"=\s*ANY\s*\(\(?ARRAY\[(.*?)\]\)?\)", r"IN (\1)", s)
    return s


def translate_default(default):
    if default is None:
        return None
    d = default.strip()
    if d.lower() in ("now()", "current_timestamp", "clock_timestamp()"):
        return "CURRENT_TIMESTAMP"
    if d in ("true", "false"):
        return "1" if d == "true" else "0"
    m = re.fullmatch(r"\((?:CURRENT_TIMESTAMP|now\(\)) \+ '(\d+):(\d+):(\d+)'::interval\)", d)
    if m:
        secs = int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3))
        return f"(datetime('now', '+{secs} seconds'))"
    m = re.fullmatch(r"\((?:CURRENT_TIMESTAMP|now\(\)) \+ '(\d+) (\w+?)s?'::interval\)", d)
    if m:
        return f"(datetime('now', '+{m.group(1)} {m.group(2)}s'))"
    d = CAST_RE.sub("", d).strip()
    while d.startswith("(") and d.endswith(")"):
        d = d[1:-1].strip()
    if re.fullmatch(r"'-?\d+(\.\d+)?'", d):
        return d[1:-1]
    if re.fullmatch(r"-?\d+(\.\d+)?", d):
        return d
    if d == "'{}'":  # empty PostgreSQL array -> empty JSON array
        return "'[]'"
    if re.fullmatch(r"'(?:[^']|'')*'", d):
        return d
    raise ValueError(f"untranslated column default: {default!r}")


def sql_literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float, Decimal)):
        return str(v)
    if isinstance(v, (datetime, date)):
        return "'" + v.isoformat(sep=" ") + "'"
    if isinstance(v, (list, dict)):
        v = json.dumps(v)
    return "'" + str(v).replace("'", "''") + "'"


def generate(dsn: str) -> str:
    import psycopg

    conn = psycopg.connect(dsn)
    cur = conn.cursor()
    cur.execute(
        "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname"
    )
    tables = [r[0] for r in cur.fetchall()]

    out = [
        "-- Generated by database_functions/sqlite_baseline.py from a freshly migrated PostgreSQL",
        "-- database. Do not edit by hand; regenerate instead.",
    ]
    cur.execute('SELECT version FROM "schema_migrations" ORDER BY version')
    versions = [r[0] for r in cur.fetchall()]
    out.append("-- baseline-versions: " + " ".join(versions))
    out.append("")

    seeds = []
    for t in tables:
        if t == "schema_migrations":
            continue
        cur.execute(
            "SELECT column_name, data_type, column_default, is_nullable, is_identity "
            "FROM information_schema.columns WHERE table_schema = 'public' AND table_name = %s "
            "ORDER BY ordinal_position",
            (t,),
        )
        cols = cur.fetchall()
        cur.execute(
            "SELECT contype, pg_get_constraintdef(oid) FROM pg_constraint "
            "WHERE conrelid = %s::regclass ORDER BY contype, conname",
            (f'"{t}"',),
        )
        cons = cur.fetchall()
        pk_cols = []
        for contype, defn in cons:
            if contype == "p":
                pk_cols = [c.strip().strip('"') for c in re.match(r"PRIMARY KEY \((.*)\)", defn).group(1).split(",")]

        lines = []
        for name, dtype, default, nullable, identity in cols:
            qname = f'"{name}"' if name != name.lower() or name in ("timestamp", "action") else name
            serial = (default or "").startswith("nextval(") or identity == "YES"
            if serial:
                if pk_cols != [name]:
                    raise ValueError(f"{t}.{name}: serial column that isn't the sole primary key")
                lines.append(f"    {qname} INTEGER PRIMARY KEY AUTOINCREMENT")
                continue
            parts = [f"    {qname} {TYPE_MAP[dtype]}"]
            if len(pk_cols) == 1 and pk_cols == [name]:
                parts.append("PRIMARY KEY")
            if nullable == "NO" and pk_cols != [name]:
                parts.append("NOT NULL")
            d = translate_default(default)
            if d is not None:
                parts.append(f"DEFAULT {d}")
            lines.append(" ".join(parts))
        if len(pk_cols) > 1:
            lines.append("    PRIMARY KEY (" + ", ".join(pk_cols) + ")")
        for contype, defn in cons:
            if contype in ("u", "f"):
                lines.append("    " + defn.replace("public.", ""))
            elif contype == "c":
                lines.append("    " + translate_expr(defn))
        out.append(f'CREATE TABLE "{t}" (\n' + ",\n".join(lines) + "\n);")

        # Seed rows (only the tables migrations populate on a fresh install).
        cur.execute(f'SELECT * FROM "{t}"')
        rows = cur.fetchall()
        if rows:
            names = [d.name for d in cur.description]
            defaults = {c[0]: c[2] for c in cols}
            for row in rows:
                ins_cols, vals = [], []
                for n, v in zip(names, row):
                    dflt = (defaults.get(n) or "").lower()
                    if dflt in ("now()", "current_timestamp", "clock_timestamp()"):
                        continue  # let the install time stand
                    if v is None and defaults.get(n) is None:
                        continue
                    ins_cols.append(n)
                    vals.append(INSTALL_PLACEHOLDERS.get((t, n), sql_literal(v)))
                seeds.append(f'INSERT INTO "{t}" (' + ", ".join(ins_cols) + ") VALUES (" + ", ".join(vals) + ");")
    out.append("")

    cur.execute(
        "SELECT indexdef FROM pg_indexes WHERE schemaname = 'public' "
        "AND indexname NOT IN (SELECT conname FROM pg_constraint) ORDER BY tablename, indexname"
    )
    for (idx,) in cur.fetchall():
        if "to_tsvector" in idx:
            continue  # PostgreSQL full-text index; SQLite searches without one
        idx = idx.replace("public.", "")
        idx = re.sub(r" USING (btree|hash|gin|gist)", "", idx)
        idx = translate_expr(idx)
        out.append(idx + ";")
    out.append("")
    # Users first: the other seed rows reference them.
    seeds.sort(key=lambda s: not s.startswith('INSERT INTO "Users"'))
    out.extend(seeds)
    conn.close()
    return "\n".join(out) + "\n"


def baseline_versions() -> list:
    with open(BASELINE_PATH) as f:
        for line in f:
            if line.startswith("-- baseline-versions:"):
                return line.split(":", 1)[1].split()
    return []


def apply_baseline(conn):
    """Create the schema and seed rows in an empty SQLite database."""
    from argon2 import PasswordHasher
    from cryptography.fernet import Fernet

    with open(BASELINE_PATH) as f:
        script = f.read()
    alphabet = string.ascii_letters + string.digits
    params = {
        "encryption_key": Fernet.generate_key().decode(),
        "bg_api_key": "".join(secrets.choice(alphabet) for _ in range(64)),
        "bg_password_hash": PasswordHasher().hash(secrets.token_urlsafe(24)),
    }
    cur = conn.cursor()
    for stmt in split_statements(script):
        if ":" in stmt and stmt.lstrip().upper().startswith("INSERT") and re.search(r":(encryption_key|bg_api_key|bg_password_hash)\b", stmt):
            cur.execute(stmt, params)
        else:
            cur.execute(stmt)
    create_env_admin(cur)
    conn.commit()


def create_env_admin(cur):
    """Same as migration 004: an admin from FULLNAME/USERNAME/EMAIL/PASSWORD, when all are set."""
    from argon2 import PasswordHasher

    fullname, username = os.environ.get("FULLNAME"), os.environ.get("USERNAME")
    email, password = os.environ.get("EMAIL"), os.environ.get("PASSWORD")
    if not all([fullname, username, email, password]):
        return
    cur.execute(
        'INSERT INTO "Users" (fullname, username, email, hashed_pw, isadmin) VALUES (?, ?, ?, ?, 1) '
        "ON CONFLICT (username) DO NOTHING RETURNING userid",
        (fullname, username.lower(), email, PasswordHasher().hash(password)),
    )
    row = cur.fetchone()
    if row:
        cur.execute('INSERT INTO "UserStats" (userid) VALUES (?)', (row[0],))
        cur.execute('INSERT INTO "UserSettings" (userid, theme) VALUES (?, ?)', (row[0], "Nordic"))


def split_statements(script: str):
    stmt, in_str = [], False
    for line in script.splitlines():
        if not in_str and (line.startswith("--") or not line.strip()):
            continue
        stmt.append(line)
        in_str ^= line.count("'") % 2 == 1
        if not in_str and line.rstrip().endswith(";"):
            yield "\n".join(stmt)
            stmt = []


if __name__ == "__main__":
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) != 1:
        sys.exit("usage: python -m database_functions.sqlite_baseline [--check] <postgresql dsn>")
    sql = generate(args[0])
    if check:
        with open(BASELINE_PATH) as f:
            if f.read() != sql:
                sys.exit(
                    "sqlite_baseline.sql doesn't match the migrations. Regenerate it from a freshly "
                    "migrated PostgreSQL database:\n"
                    "    python -m database_functions.sqlite_baseline <postgresql dsn>\n"
                    "and give any migration newer than the old baseline a SQLite branch (sqlite=True)."
                )
        print("sqlite_baseline.sql is up to date")
    else:
        with open(BASELINE_PATH, "w") as f:
            f.write(sql)
        print(f"wrote {BASELINE_PATH}")
